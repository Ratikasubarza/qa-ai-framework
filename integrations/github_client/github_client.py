"""
MCP GitHub Client — Post QA results to GitHub PRs.

Capabilities:
  - post_pr_comment()       : post test result summary as PR comment
  - get_pr_info()           : fetch PR title, branch, author
  - list_pr_files()         : list changed files in a PR (for impact analysis)
  - create_check_run()      : create a GitHub check run with pass/fail status

Env vars required:
  GITHUB_TOKEN              : Personal access token or Actions token
  GITHUB_REPOSITORY         : owner/repo  (e.g. "myorg/hono-app")
"""
from __future__ import annotations

import os
import httpx
import structlog
from dotenv import load_dotenv

load_dotenv(dotenv_path=".env")
logger = structlog.get_logger(__name__)

_GITHUB_API = "https://api.github.com"


class GitHubClient:
    def __init__(self) -> None:
        self.token = os.getenv("GITHUB_TOKEN", "")
        self.repo  = os.getenv("GITHUB_REPOSITORY", "")
        self._headers = {
            "Authorization": f"Bearer {self.token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        }

    # ── PR info ───────────────────────────────────────────────────────────────

    def get_pr_info(self, pr_number: int) -> dict:
        """Return title, branch, author, and URL for a given PR."""
        url = f"{_GITHUB_API}/repos/{self.repo}/pulls/{pr_number}"
        try:
            with httpx.Client(timeout=15) as client:
                resp = client.get(url, headers=self._headers)
            resp.raise_for_status()
            data = resp.json()
            return {
                "number": pr_number,
                "title":  data.get("title", ""),
                "author": data.get("user", {}).get("login", ""),
                "branch": data.get("head", {}).get("ref", ""),
                "url":    data.get("html_url", ""),
                "base":   data.get("base", {}).get("ref", ""),
            }
        except Exception as e:
            logger.error("github_get_pr_failed", pr=pr_number, error=str(e))
            return {}

    def list_pr_files(self, pr_number: int) -> list[str]:
        """Return list of filenames changed in the PR — useful for test impact analysis."""
        url = f"{_GITHUB_API}/repos/{self.repo}/pulls/{pr_number}/files"
        try:
            with httpx.Client(timeout=15) as client:
                resp = client.get(url, headers=self._headers)
            resp.raise_for_status()
            return [f["filename"] for f in resp.json()]
        except Exception as e:
            logger.error("github_list_files_failed", pr=pr_number, error=str(e))
            return []

    # ── PR comments ───────────────────────────────────────────────────────────

    def post_pr_comment(self, pr_number: int, body: str) -> bool:
        """Post a markdown comment on a PR. Returns True on success."""
        if not self.token or not self.repo:
            logger.warning("github_client_not_configured")
            return False
        url = f"{_GITHUB_API}/repos/{self.repo}/issues/{pr_number}/comments"
        try:
            with httpx.Client(timeout=15) as client:
                resp = client.post(url, headers=self._headers, json={"body": body})
            resp.raise_for_status()
            logger.info("github_pr_comment_posted", pr=pr_number)
            return True
        except Exception as e:
            logger.error("github_post_comment_failed", pr=pr_number, error=str(e))
            return False

    def post_qa_summary(
        self,
        pr_number: int,
        passed: int,
        failed: int,
        coverage_pct: float,
        suite_lines: list[str] | None = None,
        run_url: str = "",
    ) -> bool:
        """Post a formatted QA test result summary to a PR."""
        status = "✅ ALL PASSED" if failed == 0 else f"❌ {failed} FAILED"
        suites = "\n".join(f"  {line}" for line in (suite_lines or []))
        body = (
            f"## {status} — QA Automation Results\n\n"
            f"| Metric | Value |\n"
            f"|--------|-------|\n"
            f"| Passed | {passed} |\n"
            f"| Failed | {failed} |\n"
            f"| Coverage | {coverage_pct:.0f}% |\n\n"
        )
        if suites:
            body += f"**Suites:**\n```\n{suites}\n```\n\n"
        if run_url:
            body += f"[View full run]({run_url})\n"
        body += "\n> 🤖 Generated by QA AI Framework"
        return self.post_pr_comment(pr_number, body)

    # ── Check runs ────────────────────────────────────────────────────────────

    def create_check_run(
        self,
        name: str,
        head_sha: str,
        conclusion: str,
        title: str,
        summary: str,
    ) -> bool:
        """Create a GitHub check run (appears in PR checks list).

        conclusion: "success" | "failure" | "neutral" | "cancelled" | "skipped"
        """
        if not self.token or not self.repo:
            logger.warning("github_client_not_configured")
            return False
        url = f"{_GITHUB_API}/repos/{self.repo}/check-runs"
        payload = {
            "name":       name,
            "head_sha":   head_sha,
            "status":     "completed",
            "conclusion": conclusion,
            "output":     {"title": title, "summary": summary},
        }
        try:
            with httpx.Client(timeout=15) as client:
                resp = client.post(url, headers=self._headers, json=payload)
            resp.raise_for_status()
            logger.info("github_check_run_created", name=name, conclusion=conclusion)
            return True
        except Exception as e:
            logger.error("github_check_run_failed", name=name, error=str(e))
            return False

    # ── Workflow dispatch ─────────────────────────────────────────────────────

    def trigger_workflow(
        self,
        workflow_id: str,
        inputs: dict[str, str] | None = None,
        ref: str = "main",
    ) -> bool:
        """
        Trigger a GitHub Actions workflow_dispatch.

        workflow_id can be workflow filename (e.g. qa-pipeline.yml) or numeric ID.
        """
        if not self.token or not self.repo:
            logger.warning("github_client_not_configured")
            return False

        url = f"{_GITHUB_API}/repos/{self.repo}/actions/workflows/{workflow_id}/dispatches"
        payload = {"ref": ref, "inputs": inputs or {}}
        try:
            with httpx.Client(timeout=15) as client:
                resp = client.post(url, headers=self._headers, json=payload)
            if resp.status_code == 204:
                logger.info("github_workflow_triggered", workflow_id=workflow_id, ref=ref)
                return True

            logger.error(
                "github_workflow_trigger_failed",
                workflow_id=workflow_id,
                status=resp.status_code,
                body=resp.text[:200],
            )
            return False
        except Exception as e:
            logger.error("github_workflow_trigger_failed", workflow_id=workflow_id, error=str(e))
            return False


github_client = GitHubClient()
